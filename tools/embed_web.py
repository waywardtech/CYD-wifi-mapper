"""PlatformIO pre-build step: gzip web/index.html into src/web_assets.h.

Also runnable directly:  python tools/embed_web.py
"""
import gzip
import os

try:
    Import("env")  # type: ignore  # noqa: F821  (provided by PlatformIO)
    ROOT = env["PROJECT_DIR"]  # type: ignore  # noqa: F821
except Exception:
    ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

SRC = os.path.join(ROOT, "web", "index.html")
DST = os.path.join(ROOT, "src", "web_assets.h")


def main():
    with open(SRC, "rb") as f:
        raw = f.read()
    gz = gzip.compress(raw, 9, mtime=0)
    rows = []
    for i in range(0, len(gz), 16):
        rows.append("  " + ",".join("0x%02x" % b for b in gz[i:i + 16]))
    out = (
        "// GENERATED by tools/embed_web.py from web/index.html - do not edit.\n"
        "#pragma once\n#include <Arduino.h>\n"
        "const size_t WEB_INDEX_GZ_LEN = %d;\n"
        "const uint8_t WEB_INDEX_GZ[] PROGMEM = {\n%s\n};\n" % (len(gz), ",\n".join(rows))
    )
    old = None
    if os.path.exists(DST):
        with open(DST) as f:
            old = f.read()
    if old != out:
        with open(DST, "w") as f:
            f.write(out)
        print("embed_web: wrote %s (%d -> %d bytes gz)" % (DST, len(raw), len(gz)))


main()
